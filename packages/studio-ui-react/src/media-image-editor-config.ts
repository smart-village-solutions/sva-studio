export const createMediaImageEditorConfig = (
  element: HTMLElement,
  t: (key: string) => string
): Partial<FilerobotImageEditorConfig> => {
  const style = getComputedStyle(element);
  const color = (token: string) => `rgb(${style.getPropertyValue(`--${token}`).trim()})`;
  const palette = Object.fromEntries([
    ...['bg-primary', 'bg-secondary', 'bg-base-light', 'bg-stateless'].map((key) => [
      key,
      color('card'),
    ]),
    ...['bg-primary-light', 'bg-primary-hover', 'bg-hover', 'bg-base-medium', 'bg-grey'].map(
      (key) => [key, color('muted')]
    ),
    ...['bg-primary-active', 'bg-active'].map((key) => [key, color('accent')]),
    ...['txt-primary', 'icon-primary', 'icons-secondary', 'btn-secondary-text'].map((key) => [
      key,
      color('foreground'),
    ]),
    ...['txt-secondary', 'txt-placeholder', 'icons-muted'].map((key) => [
      key,
      color('muted-foreground'),
    ]),
    ...['borders-primary', 'borders-secondary', 'borders-button', 'borders-item'].map((key) => [
      key,
      color('border'),
    ]),
    ['accent-primary', color('action-primary')],
    ['accent-primary-hover', color('action-primary-hover')],
    ['accent-primary-active', color('action-primary-active')],
    ['btn-primary-text', color('action-primary-foreground')],
    ['txt-error', color('destructive')],
  ]);
  return {
    tabsIds: ['Adjust', 'Finetune', 'Filters', 'Annotate', 'Watermark', 'Resize'],
    defaultTabId: 'Adjust',
    defaultToolId: 'Crop',
    useBackendTranslations: false,
    useAiTab: false,
    useCloudimage: false,
    translations: Object.fromEntries(translationKeys.map((key) => [key, t(`filerobot.${key}`)])),
    theme: { palette, typography: { fontFamily: style.fontFamily } },
    Text: {
      text: t('editor.defaultText'),
      fontFamily: 'Fira Sans',
      fonts: ['Fira Sans', 'Arial', 'serif', 'monospace'],
    },
    Image: { gallery: [] },
    Watermark: { gallery: [] },
    savingPixelRatio: 1,
    previewPixelRatio: 1,
    removeSaveButton: true,
    avoidChangesNotSavedAlertOnLeave: true,
    observePluginContainerSize: true,
    Crop: {
      presetsItems: [
        { titleKey: 'square', ratio: 1 },
        { titleKey: 'landscape', ratio: 16 / 9 },
        { titleKey: 'portrait', ratio: 3 / 4 },
      ],
      presetsFolders: [],
    },
  };
};
